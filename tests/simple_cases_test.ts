import assert from "node:assert/strict";
import { test } from "node:test";
import { decompress } from "../dist/index.js";

test("Decompression of 'Ok' text", () => {
  const data = [
    0x28, 0xb5, 0x2f, 0xfd, 0x24, 0x02, 0x11, 0x00, 0x00, 0x4f, 0x6b, 0x64, 0x50, 0xa9, 0x5a,
  ];
  const compressed = new Uint8Array(data);
  const decompressed = decompress(compressed);
  const shouldBeOk = new TextDecoder().decode(decompressed);
  assert.equal(shouldBeOk, "Ok");
});

