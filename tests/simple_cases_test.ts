test("Decompression of 1 000 000 nuls", () => {
  const data = [
    0x28, 0xb5, 0x2f, 0xfd, 0xa4, 0x40, 0x42, 0x0f, 0x00, 0x54, 0x00, 0x00, 0x10, 0x00, 0x00, 0x01,
    0x00, 0xfb, 0xff, 0x39, 0xc0, 0x02, 0x02, 0x00, 0x10, 0x00, 0x02, 0x00, 0x10, 0x00, 0x02, 0x00,
    0x10, 0x00, 0x02, 0x00, 0x10, 0x00, 0x02, 0x00, 0x10, 0x00, 0x02, 0x00, 0x10, 0x00, 0x03, 0x12,
    0x0a, 0x00, 0xcc, 0xae, 0xca, 0x39,
  ];
  const compressed = new Uint8Array(data);
  const decompressed: Uint8Array = decompress(compressed);
  const arraySum = decompressed.reduce(
    (accumulator, currentValue) => accumulator + currentValue,
    0,
  );
  assert.equal(decompressed.length, 1_000_000);
  assert.equal(arraySum, 0);
});
